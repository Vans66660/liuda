// Build-time conversion only. The client keeps existing GCJ-02 GPS and gates.
const fs = require('fs'), path = require('path'), crypto = require('crypto')
const convert = require('./vendor/coordtransform.cjs')
const geo = require('../miniprogram/utils/geo')
const root = path.resolve(__dirname, '..')
const input = fs.readFileSync(path.join(root, 'docs/campus/uibe/data/uibe-osm-wgs84.geojson'))
const source = JSON.parse(input)
const gcj = c => convert.wgs84togcj02(c[0], c[1])
const originCoords = gcj([116.42145,39.97892])
const origin = { longitude:originCoords[0],latitude:originCoords[1],coordinateSystem:'gcj02' }
const project = c => { const g=gcj(c),p=geo.local({longitude:g[0],latitude:g[1]},origin);return [p.x,p.z] }
const items = source.features.map(f => ({ id:f.properties.osm_id,layer:f.properties.layer,tags:f.properties.tags,
  points:(f.geometry.type==='Polygon' ? f.geometry.coordinates[0] : f.geometry.coordinates).map(project) }))
const boundary = items.find(f=>f.layer==='campus').points
const xs=boundary.map(c=>c[0]),ys=boundary.map(c=>c[1])
const bounds={ left:Math.min(...xs)-28,right:Math.max(...xs)+28,top:Math.min(...ys)-28,bottom:Math.max(...ys)+28 }
const labels=items.filter(f=>['building','sport'].includes(f.layer)&&f.tags.name).map(f=>{
  const unique=f.points.slice(0,-1), n=unique.length
  return { id:f.id,name:f.tags.name.replace('对外经济贸易大学',''),x:unique.reduce((s,p)=>s+p[0],0)/n,z:unique.reduce((s,p)=>s+p[1],0)/n }
})
const metadata={ version:1,title:'贸大夜游',origin,bounds,boundary,labels,
  draftAreas:[{left:115,right:bounds.right-35,top:bounds.top+45,bottom:-30,label:'东北片区 · 建筑待补绘'}],
  image:'/assets/campus/uibe-night.jpg',coordinateSystem:'gcj02',fieldVerified:false,
  attribution:'© OpenStreetMap contributors · ODbL',
  sourceSha256:crypto.createHash('sha256').update(input).digest('hex'),
  coordinateConversion:'Approximate WGS84 → GCJ-02; wandergis/coordtransform (MIT); not surveyed',
  sourceDate:'2026-10-27',missingDetail:'东北片区等部分建筑待补绘；现有轮廓待校准' }
fs.writeFileSync(path.join(root,'miniprogram/data/campus.js'),
  '// Generated by scripts/prepare-campus-map.cjs. OSM data © contributors, ODbL.\nmodule.exports = '+JSON.stringify(metadata,null,2)+'\n')
fs.writeFileSync(path.join(root,'docs/campus/uibe/data/campus-render.json'),JSON.stringify({metadata,items},null,2)+'\n')
console.log('Prepared',items.length,'GCJ-02 reference features; coordinates are approximate, not field-verified')
